-- MD Dance Academy staff back end (applied as migrations md_dance_staff_backend and md_revoke_anon_helpers, 10 Nov 2026).
-- Full SQL lives in supabase_migrations.schema_migrations; this file records the shape.
--
-- Tables (all RLS on, anon revoked):
--   md_staff       staff logins linked to auth.users; role Principal or Coach; active flag removes access
--   md_classes     the weekly timetable; code matches the website's class ids (mon-kids, sat-kids, ...); coach_id
--   md_families    parent or guardian contact details
--   md_dancers     dancers per family, age, level, medical notes, photo consent
--   md_enrolments  dancer in class, active or ended
--   md_attendance  registers: class, dancer, date, present
--   md_requests    free trial and term enrolment requests from the website
--   md_charges / md_payments  fees owed and paid per family (balance = charges - payments)
--   md_orders      shop orders, paid at collection
--   md_events / md_entries    term dates, medals, shows, competitions and who is entered
--   md_messages    website contact form
--   md_lessons / md_lesson_dancers  private and pair lessons: date, start, end, coach, venue, typed price, status
--                  (booked, taught, cancelled), keep_charge for late cancellations; series_id links weekly repeats
--
-- Who sees what:
--   md_is_principal()  active Principal, or Dunnworks (dw_is_owner): everything
--   md_teaches(class)  principal, or the class's coach
--   md_sees_dancer()   principal, or coach of a class the dancer is actively in
--   Coaches see their classes' dancers, families, registers, trial requests and entries; never fees, orders or messages.
--   md_clear_demo()    principal only; deletes rows flagged demo (sample families, bookings, orders, events, messages)
--
-- Lessons (migrations md_lessons_timetable, md_staff_visible_to_staff): every active staff member sees and edits
--   the whole timetable and all staff names. md_sync_lesson() keeps md_charges in step: once a lesson's day
--   arrives its price is charged, split evenly across the dancers' families; cancelled lessons only if keep_charge.
--   Cron job md-lesson-charges runs md_charge_due_lessons() daily at 00:10 UTC. md_dancer_directory() gives staff
--   every active dancer's name, age, medical note and parent contact for picking dancers into lessons.
--
-- Notifications (migration md_push_and_realtime): md_push_subs holds each staff phone's push subscription (own rows only);
--   md_private (no client access) holds the VAPID keys and the internal key md-public uses to call md-push.
--   md_requests, md_lessons, md_orders and md_messages are in the realtime publication so the app refreshes itself.
--
-- Writes from the public website go only through the md-public edge function (service role, rate limited,
-- honeypot). Staff logins are created by principals through the md-staff edge function.
-- Emails (md_private): notify_to lists who gets website booking emails (Dunnworks and MD), sent one by one;
--   mail_from is the sender, which must be on a domain verified in Resend before MD's copy can arrive.
-- Password reset (migration md_reset_and_reminders): md-reset edge function emails a one-hour link to the staff app
--   (#reset=token); md_reset_tokens holds only a SHA-256 of each token, has no client access, 3 links per login per hour.
-- 4pm reminders: cron job md-4pm-reminders calls md-push kind 'reminders' at 15:00 and 16:00 UTC; it only sends when
--   it is 4pm in London, listing each coach's booked lessons and group classes that day.
-- Parent app (migration md_parent_app_and_monthly, page preview/md-dance-academy/parents/): md_families.user_id links a
--   family to the login that owns its email. Parents never read tables; md_parent_home() returns their own family's
--   dancers, classes, lessons, fees, statement and events, md_parent_enter() enters or withdraws a dancer from an open
--   future event (not once paid), md_parent_update() changes their name, phone, and dancers' medical notes and photo
--   consent. md-reset 'request' with app 'parent' makes the login the first time; 'invite' lets a principal email a
--   seven-day set-up link. md-push 'parent' tells principals about entries and detail changes.
-- Monthly email (md-monthly, cron md-monthly-email daily 08:05 UTC): two days before the 1st principals get a preview
--   email and phone alert; on the 1st each real family (email, active dancer, not demo) gets fees owed, weekly
--   classes, that month's lessons, events entered, events open for entries and other dates. md_mailings holds each
--   month's status (scheduled, held, sending, sent) and principals can hold it from Fees; md_mail_log records sends.
-- Demo logins: md.principal@preview.dunnworks.io and md.coach@preview.dunnworks.io, and parent md.parent@preview.dunnworks.io
--   (Sarah Whitfield's sample family). Remove before real data.
